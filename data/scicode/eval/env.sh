#!/usr/bin/env bash
# Source this file. It intentionally keeps caches on VEPFS.
SCICODE_REPO_ROOT="${SCICODE_REPO_ROOT:-$(pwd)}"
export SCICODE_REPO_ROOT

export SCICODE_EXTERNAL="${SCICODE_EXTERNAL:-$SCICODE_REPO_ROOT/external/SciCode}"
export SCICODE_DATA_ROOT="${SCICODE_DATA_ROOT:-$SCICODE_REPO_ROOT/data/scicode}"
export SCICODE_CACHE_ROOT="${SCICODE_CACHE_ROOT:-/vepfs-mlp2/c20250203/250602012/cache/scicode}"

export HF_HOME="${HF_HOME:-$SCICODE_CACHE_ROOT/huggingface}"
export HUGGINGFACE_HUB_CACHE="${HUGGINGFACE_HUB_CACHE:-$HF_HOME/hub}"
export PIP_CACHE_DIR="${PIP_CACHE_DIR:-$SCICODE_CACHE_ROOT/pip}"
export XDG_CACHE_HOME="${XDG_CACHE_HOME:-$SCICODE_CACHE_ROOT/xdg}"
export TMPDIR="${TMPDIR:-$SCICODE_CACHE_ROOT/tmp}"

mkdir -p "$SCICODE_CACHE_ROOT" "$HF_HOME" "$PIP_CACHE_DIR" "$XDG_CACHE_HOME" "$TMPDIR" "$SCICODE_DATA_ROOT/cache"
